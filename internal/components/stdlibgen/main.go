// Command stdlibgen generates the embedded standard-library reference used by
// the component and dependency analyzer.
//
// Run with: go generate ./internal/components
//
// The reference is produced from the Go toolchain compiling Forgehand, so it
// is authoritative for exactly one Go release (the analyzer's own). It reads
// the local (offline) `go list std` output and requires no network access.
package main

import (
	"fmt"
	"io"
	"os"
	"os/exec"
	"runtime"
	"sort"
	"strings"
)

const (
	packagesFile  = "stdlib.txt"
	versionFile   = "stdlib_version.go"
	packageHeader = "package components\n"
)

func main() {
	output, err := exec.Command("go", "list", "std").Output()
	if err != nil {
		fmt.Fprintf(os.Stderr, "stdlibgen: go list std: %v\n", err)
		os.Exit(1)
	}

	set := make(map[string]struct{})
	for _, line := range strings.Split(string(output), "\n") {
		line = deVendor(strings.TrimSpace(line))
		if line == "" {
			continue
		}
		set[line] = struct{}{}
	}

	packages := make([]string, 0, len(set))
	for pkg := range set {
		packages = append(packages, pkg)
	}
	sort.Strings(packages)

	if err := writeFile(packagesFile, strings.Join(packages, "\n")+"\n"); err != nil {
		fmt.Fprintf(os.Stderr, "stdlibgen: write %s: %v\n", packagesFile, err)
		os.Exit(1)
	}

	reference := runtime.Version()
	if !strings.HasPrefix(reference, "go") {
		reference = "unknown"
	}
	versionSource := fmt.Sprintf(
		"%s// Code generated by go generate; DO NOT EDIT.\n\n"+
			"// stdlibReferenceVersion is the Go toolchain version that produced\n"+
			"// stdlib.txt. The standard-library reference is authoritative only\n"+
			"// for this version.\n"+
			"const stdlibReferenceVersion = %q\n",
		packageHeader,
		reference,
	)
	if err := writeFile(versionFile, versionSource); err != nil {
		fmt.Fprintf(os.Stderr, "stdlibgen: write %s: %v\n", versionFile, err)
		os.Exit(1)
	}

	fmt.Fprintf(
		os.Stderr,
		"stdlibgen: wrote %d packages for %s\n",
		len(packages),
		reference,
	)
}

// deVendor maps vendored standard-library import paths to the canonical import
// paths users actually write. For example the toolchain reports
// "vendor/golang.org/x/net/idna" but user source imports "golang.org/x/net/idna".
func deVendor(importPath string) string {
	return strings.TrimPrefix(importPath, "vendor/")
}

func writeFile(name string, content string) error {
	file, err := os.Create(name)
	if err != nil {
		return err
	}
	defer file.Close()
	_, err = io.WriteString(file, content)
	return err
}
